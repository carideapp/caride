/// Elevation tokens for the Liquid Glass design system.
abstract final class AppElevations {
  /// Flat / no elevation.
  static const double none = 0;

  /// Subtle lift for cards resting on a surface.
  static const double card = 1;

  /// Slightly raised elements (buttons, chips).
  static const double raised = 2;

  /// Floating elements (FABs, bottom sheets).
  static const double floating = 4;

  /// Modal / overlay surfaces.
  static const double modal = 8;

  /// Top-layer elements (navigation bar).
  static const double top = 12;
}
