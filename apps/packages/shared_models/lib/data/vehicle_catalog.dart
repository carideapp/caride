  /// List of valid vehicle model years (descending from next year down to 2000).
  static List<int> get validYears {
    final currentYear = DateTime.now().year;
    final maxYear = currentYear + 1;
    const minYear = 2000;
    return List.generate(maxYear - minYear + 1, (i) => maxYear - i);
  }
